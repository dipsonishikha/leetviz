#!/usr/bin/env bash
# Installs every compiler / runtime / debugger the LeetViz server needs into
# server/.toolchains (no root needed). Re-running skips what is already there.
#
#   ./scripts/install-toolchains.sh            # everything
#   ./scripts/install-toolchains.sh swift dart # just these
set -uo pipefail
FAILED=()

HERE="$(cd "$(dirname "$0")/.." && pwd)"
TC="${LEETVIZ_TOOLCHAINS:-$HERE/.toolchains}"
mkdir -p "$TC/bin" "$TC/opt"
cd "$TC"

want() { [ $# -eq 0 ] || [ -z "${ONLY:-}" ] || [[ " $ONLY " == *" $1 "* ]]; }
ONLY="$*"
log() { printf '\n== %s\n' "$*"; }
fail() { echo "!! $1 failed"; FAILED+=("$1"); }

# ---------------------------------------------------------------- conda-forge packages
if [ ! -x bin/micromamba ]; then
  log micromamba
  curl -fsSL https://micro.mamba.pm/api/micromamba/linux-64/latest | tar -xj bin/micromamba
fi
MM="$TC/bin/micromamba"
CONDA_PKGS=(gcc gxx gdb python=3.12 nodejs openjdk=21 kotlin go delve rust ruby php erlang elixir racket dotnet lldb)
if want conda && [ ! -x root/bin/kotlinc ]; then
  log "conda-forge: ${CONDA_PKGS[*]}"
  "$MM" create -y -q -r "$TC/root" -n lv -c conda-forge "${CONDA_PKGS[@]}" || fail conda
fi
ENV="$TC/root/envs/lv"

# ---------------------------------------------------------------- Scala 3 (coursier)
if want scala && [ ! -x opt/scala/bin/scalac ]; then (
  set -e
  log "Scala 3"
  curl -fsSL https://github.com/coursier/coursier/releases/latest/download/cs-x86_64-pc-linux.gz | gzip -d > bin/cs
  chmod +x bin/cs
  JAVA_HOME="$ENV/lib/jvm" PATH="$ENV/bin:$PATH" bin/cs install --install-dir opt/scala/bin scala3-compiler:3.7.3 scala3-runner:3.7.3 2>/dev/null \
    || JAVA_HOME="$ENV/lib/jvm" PATH="$ENV/bin:$PATH" bin/cs install --install-dir opt/scala/bin scalac scala
  [ -x opt/scala/bin/scalac ] || ln -sf scala3-compiler opt/scala/bin/scalac
) || fail scala; fi

# ---------------------------------------------------------------- Dart
if want dart && [ ! -x opt/dart-sdk/bin/dart ]; then (
  set -e
  log Dart
  curl -fsSL -o /tmp/lv-dart.zip https://storage.googleapis.com/dart-archive/channels/stable/release/latest/sdk/dartsdk-linux-x64-release.zip
  python3 -c "import zipfile,sys; zipfile.ZipFile(sys.argv[1]).extractall(sys.argv[2])" /tmp/lv-dart.zip opt
  chmod +x opt/dart-sdk/bin/* opt/dart-sdk/bin/utils/* 2>/dev/null || true
  rm -f /tmp/lv-dart.zip
) || fail dart; fi

# ---------------------------------------------------------------- Swift (includes lldb)
if want swift && [ ! -x opt/swift/usr/bin/swiftc -o ! -f opt/swift/.complete ]; then (
  set -e
  log Swift
  ver="$(curl -fsSL https://www.swift.org/api/v1/install/releases.json | python3 -c 'import json,sys; print(json.load(sys.stdin)[-1]["name"])')"
  url="https://download.swift.org/swift-$ver-release/ubuntu2404/swift-$ver-RELEASE/swift-$ver-RELEASE-ubuntu24.04.tar.gz"
  rm -rf opt/swift && mkdir -p opt/swift
  curl -fL --retry 8 --retry-all-errors -C - -o /tmp/lv-swift.tgz "$url"
  tar -xzf /tmp/lv-swift.tgz -C opt/swift --strip-components=1 && rm -f /tmp/lv-swift.tgz && touch opt/swift/.complete
) || fail swift; fi

# ---------------------------------------------------------------- netcoredbg (C# debugger)
if want csharp && [ ! -x opt/netcoredbg/netcoredbg ]; then (
  set -e
  log netcoredbg
  curl -fL --retry 5 -o /tmp/lv-ncdbg.tgz https://github.com/Samsung/netcoredbg/releases/latest/download/netcoredbg-linux-amd64.tar.gz
  tar -xzf /tmp/lv-ncdbg.tgz -C opt && rm -f /tmp/lv-ncdbg.tgz
) || fail netcoredbg; fi

# ---------------------------------------------------------------- env file used by the server
cat > env.sh <<EOF
# Generated by install-toolchains.sh: puts every toolchain on PATH.
export LV_TC="$TC"
export PATH="\$PATH:$TC/bin:$TC/opt/swift/usr/bin:$TC/opt/dart-sdk/bin:$TC/opt/scala/bin:$TC/opt/netcoredbg:$ENV/lib/dotnet:$ENV/libexec/kotlin/bin:$ENV/bin"
export JAVA_HOME="$ENV/lib/jvm"
export DOTNET_ROOT="$ENV/lib/dotnet"
export DOTNET_CLI_TELEMETRY_OPTOUT=1 DOTNET_NOLOGO=1 DOTNET_SKIP_FIRST_TIME_EXPERIENCE=1
export GOPATH="$TC/gopath" GOCACHE="$TC/gocache" GOFLAGS=-mod=mod GOTOOLCHAIN=local
export CARGO_HOME="$TC/cargo"
EOF
if [ ${#FAILED[@]} -gt 0 ]; then
  log "done, but these failed (re-run to retry): ${FAILED[*]}"
  exit 1
fi
log "done — source $TC/env.sh"
